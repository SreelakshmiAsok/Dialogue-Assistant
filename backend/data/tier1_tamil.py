def story_tamil(question_id):
    item = TIER1_TAMIL.get(question_id)
    return item[0] if item else ""


def answer_tamil(question_id):
    item = TIER1_TAMIL.get(question_id)
    return item[1] if item else ""


_STAR_WORDS = {1: "ஒண்ணு", 2: "ரெண்டு", 3: "மூணு", 4: "நாலு", 5: "அஞ்சு"}


def feedback_tamil(question_id, matched, stars=0, kind="normal", missing_honorific=False):
    """Everyday spoken-Tamil result for a Tier 1 evaluation.

    kind: normal | empty | inappropriate | safety
    """
    ans = answer_tamil(question_id)
    say = f" இப்படி சொல்லிப் பாரு: {ans}." if ans else ""
    if kind == "empty":
        return "பொறுமையா யோசி. ரெடி ஆனதும் மைக்க தட்டிப் பேசு." + say
    if kind == "inappropriate":
        return "நல்ல வார்த்தைய யூஸ் பண்ணலாம்." + say
    if kind == "safety":
        return "இது சேஃப்பான ஆன்சர் இல்ல." + say
    if matched:
        text = "செம! சூப்பரா சொன்ன!" if stars >= 4 else "குட்! கரெக்டா சொன்ன."
        if stars in _STAR_WORDS:
            text += f" உனக்கு {_STAR_WORDS[stars]} ஸ்டார் கிடைச்சுது."
        if missing_honorific and ans:
            text += f" மரியாதையா இப்படியும் சொல்லலாம்: {ans}."
        return text
    return "பரவால்ல, இன்னொரு தடவ ட்ரை பண்ணு." + say
